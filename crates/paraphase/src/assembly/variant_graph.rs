    /// Initialize the graph.
    pub fn init_edges(&mut self) {
        let mut node_id_map = NodeMapType::new();
        std::mem::swap(&mut node_id_map, &mut self.node_id_map); // Ownership hack: move node_id_map out of struct, modify, put back.
        log::trace!("{} reads", self.reads.len());
        let mut total_node_count = self.total_node_count;
        for (read_aln_id, hap) in self.reads.iter().filter(|(_name, hap)| {
            let num_valid = Self::count_valid(&hap[..]);
            assert_eq!(hap.len(), self.nvar);
            num_valid > 0
        }) {
            let read_name = &read_aln_id.read_name[..];
            let read_id = self.read_aln_id(read_aln_id).expect("Missing read name");
            // Skip pairs of adjacent variant positions which have either base as invalid.
            log::trace!("{read_name}:{hap} for {read_id}");
            for (window_index, window) in hap
                .windows(2)
                .enumerate()
                .filter(|x| x.1.iter().all(Self::is_valid))
            {
                let (from, to): (u8, u8) = window.iter().copied().next_tuple().unwrap();
                let from_pos = NodeDatum::from((from, window_index));
                let to_pos = NodeDatum::from((to, window_index + 1));
                let (from_id, from_was_new) =
                    Self::id_node_by_map(&mut node_id_map, &from_pos, &mut total_node_count);
                if from_was_new {
                    let graph_id = self.graph.add_node(from_pos).index() as u32;
                    assert_eq!(from_id, graph_id);
                }
                let (to_id, to_was_new) =
                    Self::id_node_by_map(&mut node_id_map, &to_pos, &mut total_node_count);
                if to_was_new {
                    let graph_id = self.graph.add_node(to_pos);
                    assert_eq!(to_id as usize, graph_id.index());
                }
                let edge_idx = if let Some(e) = self.graph.find_edge(from_id.into(), to_id.into()) {
                    self.graph.edge_weight_mut(e).unwrap().push(read_id);
                    e
                } else {
                    self.graph
                        .add_edge(from_id.into(), to_id.into(), vec![read_id])
                };
                log::trace!(
                    "from {}@{from_id}, to {}@{to_id} are assigned edge {edge_idx:?}",
                    from as char,
                    to as char
                );
            }
        }
        std::mem::swap(&mut node_id_map, &mut self.node_id_map);
        std::mem::swap(&mut total_node_count, &mut self.total_node_count);
        let id_to_node = self.get_id_lookup();
        let mut pos_edge_map: BTreeMap<usize, Vec<(u32, u32, u32)>> = BTreeMap::new();
        for i in 0..(self.nvar - 1) {
            pos_edge_map.insert(i, vec![]);
        }
        let mut edge_info: Vec<Vec<u32>> = vec![vec![]; self.nvar - 1];
        for edge in self.graph.edge_references() {
            let source = edge.source();
            let target = edge.target();
            let weight = edge.weight().len() as u32;
            let v = (source.index() as u32, target.index() as u32, weight);
            let position_index = id_to_node
                .get(&(source.index() as u32))
                .expect("error building graph")
                .pos as usize;
            pos_edge_map.entry(position_index).or_default().push(v);
            edge_info[position_index].push(weight);
        }
        self.pos_edge_map = pos_edge_map;
        self.edge_info = edge_info;
    }

    #[must_use]
    pub fn make_edge_info(&self) -> Vec<Vec<u32>> {
        let id_to_node = self
            .get_id_lookup()
            .into_iter()
            .map(|(x, y)| (x, y.to_owned()))
            .collect::<HashMap<_, _>>();
        let mut edge_info: Vec<Vec<u32>> = vec![vec![]; self.nvar - 1];
        for edge in self.graph.edge_references() {
            let source = edge.source().index() as u32;
            let weight = edge.weight().len() as u32;
            let position_index = id_to_node.get(&source).expect("error edge info").pos as usize;
            edge_info[position_index].push(weight);
        }
        edge_info
    }

    /// Check the number of different edges starting at each position.
    pub fn summarize_edges(&mut self) -> DResult {
        let mut site1 = HashSet::default();
        let mut site2 = HashSet::default();
        let mut expected_site1 = HashSet::default();
        let mut expected_site2 = HashSet::default();
        for (idx, edges) in &self.pos_edge_map {
            let idx = *idx as u32;
            let nhap: SegmentationClass = if edges.iter().map(|x| x.2).max().unwrap_or(1) > 2
                && edges.iter().map(|x| x.2).min().unwrap_or(1) >= 2
            {
                let mut dlinks: HashMap<u32, BTreeSet<u32>> = HashMap::default(); // Map from node id to set of other node ids
                for x in [
                    &mut site1,
                    &mut site2,
                    &mut expected_site1,
                    &mut expected_site2,
                ] {
                    x.clear();
                }
                for node_index in self.graph.node_indices() {
                    let node: &NodeDatum = &self.graph[node_index];
                    let base = &node.hap[..];
                    let pos = node.pos;
                    match (pos as i32) - (idx as i32) {
                        0 => {
                            expected_site1.insert(base);
                        }
                        1 => {
                            expected_site2.insert(base);
                        }
                        _ => {}
                    }
                }
                for (from_id, to_id, _count) in edges {
                    let from = &self.graph[NodeIndex::new(*from_id as usize)];
                    let to = &self.graph[NodeIndex::new(*to_id as usize)];
                    site1.insert(&from.hap[..]);
                    site2.insert(&to.hap[..]);
                    dlinks.entry(*from_id).or_default().insert(*to_id);
                }
                if (&site1, &site2) == (&expected_site1, &expected_site2) {
                    if dlinks.values().any(|x| x.len() > 1) {
                        SegmentationClass::Ten
                    } else {
                        SegmentationClass::Two
                    }
                } else {
                    SegmentationClass::Unassigned
                }
            } else {
                SegmentationClass::Unassigned
            };
            self.dnhap.insert(idx, nhap);
        }
        if self.settings.pivot_index > 0 {
            if let Some(height) = self
                .dnhap
                .get_mut(&((self.settings.pivot_index - 1) as u32))
            {
                if *height == SegmentationClass::Two {
                    *height = SegmentationClass::Ten;
                }
            }
        }
        Ok(())
    }

    /// Computes the minimum edge support for given read counts.
    /// Higher coverage samples need slightly higher thresholds.
    #[must_use]
    pub fn edge_support_threshold<T: TryInto<usize> + Copy>(num_reads: &[T]) -> u32 {
        let min_count = num_reads
            .iter()
            .map(|x| {
                (*x).try_into()
                    .unwrap_or_else(|_| panic!("Failed to convert"))
            })
            .min()
            .unwrap_or(0);
        let total_min = num_reads
            .iter()
            .map(|x| {
                (*x).try_into()
                    .unwrap_or_else(|_| panic!("Failed to convert"))
            })
            .filter(|x| *x != min_count)
            .min()
            .unwrap_or(0);
        if total_min > 10 {
            std::cmp::min(5, std::cmp::max(2, total_min / 25)) as u32
        } else {
            u32::from(total_min > 5)
        }
    }

    /// Retrieve haplotypes at position, converted to owned representations.
    /// For views alone, use `Graph::get_hap_by_pos`.
    #[must_use]
    pub fn get_owned_haps_by_pos(&self, pos: u32) -> Vec<VString> {
        self.get_hap_by_pos(pos)
            .map(VString::from)
            .collect::<Vec<_>>()
    }

    /// Assemble region in pos1..=pos2
    ///     pos1: first position used.
    ///     pos2: last position used.
    ///     `allow_x`: bool : if true, missing candidates will be output with x's appended.
    /// Returns:
    ///     bool: assembly success
    ///     `pos1_haps`: `Vec<VString>` - assembled haps.
    ///     where dnext and dbefore has pairs of connected fingerprint substrings.
    ///     dnext, dbefore: `BTreeMap<VString, BTreeSet<VString>>`.
    ///
    /// # Errors
    /// 1. `anyhow::anyhow` - missing next position.
    /// 2. `anyhow::anyhow` - merge two positions fail
    /// # Panics
    pub fn subregion_assembly(
        &mut self,
        pos1: u32,
        pos2: u32,
        allow_x: bool,
    ) -> Result<SubregionResult, DError> {
        let mut success = true;
        let mut curr_pos1 = pos1;
        let mut pos1_haps = self.get_owned_haps_by_pos(pos1);
        log::trace!("[subregion_assembly] Initial pos1_haps: {pos1_haps:?} for {pos1}..={pos2}. Pos edge map: {:?}", self.formatted_edges());
        if pos1_haps.is_empty() {
            return Err(Box::new(GraphError {
                msg: format!("pos1 haps is empty at {pos1}..={pos2}. Allow x: {allow_x}"),
            }));
        }
        assert!(!pos1_haps.is_empty());
        let mut dnext = BTreeMap::new();
        let mut dbefore = BTreeMap::new();
        let mut iternum = 1usize;
        while curr_pos1 < pos2 {
            let next_pos = self.get_next_pos(curr_pos1).ok_or_else(|| {
                anyhow::anyhow!(
                    "Missing next position: {curr_pos1} query, initial pos {pos1} and pos2 {pos2}"
                )
            })?;
            let next_haps = self.get_owned_haps_by_pos(next_pos);
            log::trace!("[subregion_assembly@{iternum}] {curr_pos1} and {pos2} assembly for initial pos1 {pos1}. Current pos1_haps: {pos1_haps:?}. And {next_haps:?} at {next_pos}. Edges at this point, before use: {:?}", self.formatted_edges());
            if ![&pos1_haps, &next_haps].iter().all(|x| !x.is_empty()) {
                return Err(Box::new(GraphError {
                    msg: format!("pos1 haps or next haps are empty. {pos1_haps:?}, {next_haps:?}"),
                }));
            }
            let mut subregion_haps_assembled = BTreeSet::new();
            if pos1_haps.len() == 1 || next_haps.len() == 1 {
                for (hap1, hap2) in iproduct!(pos1_haps.iter(), next_haps.iter()) {
                    let new_hap = {
                        let mut x = VString::from(hap1);
                        x.extend_from_slice(hap2);
                        x
                    };
                    log::trace!("[subregion_assembly@{iternum}] Merging hap1 and hap2 {hap1}/{hap2} because there was only one of each. New hap: {new_hap}. next_pos: {next_pos}. Current pos: {curr_pos1}");
                    subregion_haps_assembled.insert(new_hap);
                }
                dnext.clear();
                dbefore.clear();
            } else {
                log::trace!("[subregion_assembly@{iternum}] Complex dnext/dbefore");
                let new_nodes = [(pos1, &pos1_haps), (next_pos, &next_haps)]
                    .into_iter()
                    .map(|(k, value)| (k, value.iter().map(|x| x.vstr()).collect::<BTreeSet<_>>()))
                    .collect::<BTreeMap<_, _>>();
                let (sub_hap, dnext_new, dbefore_new) = self.merge_two_pos(&new_nodes)?;
                dnext = dnext_new
                    .into_iter()
                    .map(|(k, v)| {
                        (
                            VString::from(k),
                            v.into_iter().map(VString::from).collect::<BTreeSet<_>>(),
                        )
                    })
                    .collect::<BTreeMap<_, _>>();
                dbefore = dbefore_new
                    .into_iter()
                    .map(|(k, v)| {
                        (
                            VString::from(k),
                            v.into_iter().map(VString::from).collect::<BTreeSet<_>>(),
                        )
                    })
                    .collect::<BTreeMap<_, _>>();
                let thres = Self::get_len_threshold(pos1_haps[0].len(), next_haps[0].len());
                log::trace!("[subregion_assembly@{iternum}] from new nodes {new_nodes:?} we get dnext: {dnext:?}. dbefore: {dbefore:?} after merging two positions. Length threshold is {thres}");

                for (hap, reads) in sub_hap.iter().filter(|(_hap, reads)| reads.len() >= thres) {
                    log::trace!(
                        "[subregion_assembly@{iternum}] Adding in hap {hap:?} from merge_two_pos because {} >= {thres}",
                        reads.len()
                    );
                    subregion_haps_assembled.insert(hap.clone());
                }
                // BTreeMap<VString, Vec<&'a ReadAlignmentId>>,
            }
            let (mut left, mut right) =
                Self::get_missing(&subregion_haps_assembled, &pos1_haps, &next_haps);
            log::trace!("[subregion_assembly@{iternum}] added in new subregion_haps_assembled: {subregion_haps_assembled:?}. Missing {left:?}/{right:?}");
            if !left.is_empty() || !right.is_empty() {
                log::trace!("[subregion_assembly] allow_x is {allow_x}");
                if !allow_x {
                    log::trace!(
                        "[subregion_assembly] No allow x; returning. pos1 haps: {pos1_haps:?} with dnext/dbefore {dnext:?}/{dbefore:?} for range {pos1}..={pos2}. Edges: {:?}", self.formatted_edges(),
                    );
                    success = false;
                    return Ok((success, pos1_haps, dnext, dbefore));
                }
                let hap_len1 = pos1_haps[0].len();
                let hap_len2 = next_haps[0].len();
                if std::cmp::min(hap_len1, hap_len2) >= 3
                    && matches!(
                        self.dnhap
                            .get(&(next_pos - 1))
                            .map(SegmentationClass::is_assigned),
                        Some(true)
                    )
                    && self
                        .edge_info
                        .get(next_pos as usize - 1)
                        .and_then(|x| x.iter().copied().max())
                        .unwrap_or(0)
                        >= 2
                {
                    let mut missing = Self::rescue_missing(&left, &right, &dnext, &dbefore);
                    log::trace!("[subregion_assembly] missing rescued: {missing:?} for {left:?} and {right:?}");
                    subregion_haps_assembled.append(&mut missing);
                    (left, right) =
                        Self::get_missing(&subregion_haps_assembled, &pos1_haps, &next_haps);
                    log::trace!(
                        "[subregion_assembly] remaining missing after rescue_missing. left: {left:?}. right: {right:?}"
                    );
                } else {
                    log::trace!("[subregion_assembly] Could not rescue for left and right {left:?} and right {right:?}");
                }

                for missing in &right {
                    let mut hap = vec![b'x'; hap_len1];
                    hap.extend_from_slice(&missing[..]);
                    subregion_haps_assembled.insert(VString::from(hap));
                }
                let x_missing = vec![b'x'; hap_len2];
                for missing in &left {
                    let mut hap = (*missing).clone();
                    hap.extend_from_slice(&x_missing);
                    subregion_haps_assembled.insert(hap);
                }
            }
            pos1_haps = subregion_haps_assembled
                .into_iter()
                .collect::<Vec<VString>>();
            curr_pos1 = next_pos;
            iternum += 1;
        } // while curr_pos1 < pos2
        log::trace!("[subregion_assembly] after subregion assembly for {pos1}..={pos2}, pos_edge_map is {:?}. dnext and dbefore are {dnext:?} and {dbefore:?}. Formatted: {:?}", self.pos_edge_map, self.formatted_edges());
        Ok((success, pos1_haps, dnext, dbefore))
    }

    /// Compute read support count threshold for haplotypes of different lengths.
    /// x and y correspond to left/right hand fingerprint substrings at a given position.
    #[must_use]
    fn get_len_threshold(x: usize, y: usize) -> usize {
        let maxlen = std::cmp::max(x, y);
        let minlen = std::cmp::min(x, y);
        if minlen > 2 || (minlen == 2 && maxlen >= 10) {
            1
        } else {
            2
        }
    }

    /// Find the best matches for nodes given a query fingerprint.
    ///     Parameters:
    ///         `new_nodes` (BTreeMap): two positions and their associated partial haplotypes
    ///         pos1 (int): positions of interest
    ///         hap (str): full fingerprint
    ///     Returns:
    ///         (hap1, match)
    ///         hap1: corresponding segment in the read
    ///         match: Option<(`max_match`, `best_match`)>
    ///         `best_match`: list of best matches
    ///         `max_match`: length of the best matches
    pub fn get_matching_hap<'a, 'b, C, IntoVstr: std::convert::Into<VStr<'a>>>(
        nodes: &'a BTreeMap<u32, C>,
        pos1: u32,
        hap: VStr<'b>,
    ) -> Result<(VStr<'b>, Option<MatchingHapSet<'a>>), DError>
    where
        &'a C: std::iter::IntoIterator<Item = IntoVstr>,
    {
        let candidates = nodes
            .get(&pos1)
            .expect("Missing position")
            .into_iter()
            .map(std::convert::Into::into)
            .collect::<Vec<_>>();
        let pos1 = pos1 as usize;
        let pos2 = candidates[0].len();
        if pos1 + pos2 > hap.len() {
            return Err(Box::new(GraphError {
                msg: format!("{pos1} and {pos2} for hap {hap} is out of bounds"),
            }));
        }
        // hap1 = hap[pos1 : (pos1 + pos2)]
        let hap1 = VStr::from(&hap[pos1..(pos1 + pos2)]);
        log::trace!(
            "query hap {hap1} into candidates {candidates:?} with pos2 {pos2} and pos1 {pos1}"
        );

        let mut matches: BTreeMap<_, Vec<_>> = BTreeMap::new();
        for cand in candidates {
            let cmp = HapCompare::from_haps(&cand[..], hap1)?;
            if cmp.mismatches > 0 || cmp.matches <= 0 {
                continue;
            }
            matches.entry(cmp.matches).or_default().push(cand);
        }

        let best_match = matches
            .into_iter()
            .max_by_key(|x| x.0)
            .map(|(key, value)| (key, value.clone()));
        Ok((hap1, best_match))
    }
