pub type EdgeType = Vec<u32>; // Vector of read ids
pub type IxType = u32;
pub type VGraph = PetGraph<NodeType, EdgeType, petgraph::Directed, IxType>;
/// best match score + vector of matches sharing that score.
pub type MatchingHapSet<'a> = (i32, Vec<VStr<'a>>);

/// Settings for `Graph` haplotype assembler.
/// Most use cases will use default.
///
/// `min_match_count`: Minimum number of fingerprint positions for matching reads against candidate haplotypes. Raising this increases specificity but reduces sensitivity.
/// `min_hap_support`: Minimum number of reads supporting a haplotype for final filtering.
/// `pivot_index`: Used for partitioning the graph based on a pivot position.
///
/// Defaults to `(4, 1, 0)`.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct Settings {
    pub min_match_count: i32, /* Minimum number of fingerprint positions for matching reads against candidate haplotypes. Raising this increases specificity but reduces sensitivity. */
    pub min_hap_support: i32, /* Minimum number of reads supporting a haplotype for final filtering. */
    pub pivot_index: i64,     // Used for partitioning the graph based on a pivot position.
}

impl std::default::Default for Settings {
    fn default() -> Self {
        Self {
            min_hap_support: 4,
            min_match_count: 1,
            pivot_index: -1,
        }
    }
}

impl Settings {
    /// Construct settings from a pivot index, otherwise using defaults of 1 match for partial haplotypes and minimum 4 read support for inclusion.
    #[must_use]
    pub fn from_pivot(pivot_index: Option<i64>) -> Self {
        let pivot_index = pivot_index.unwrap_or(-1);
        log::debug!("Building settings from pivot_index {pivot_index}");
        Self {
            pivot_index,
            ..Default::default()
        }
    }
}

pub type NodeMapType = BTreeMap<NodeDatum, u32>;

/// For ease - tuple. `(from_id, to_id, count)`
pub type WeightedEdge = (u32, u32, u32);

/// `Graph` is the core data structure for haplotype assembly.
/// Using a set of extracted fingerprints, it segments the graph, assembles local regions, and then chains them
/// into a set of assembled haplotypes.
/// 50% unit test coverage currently.
/// Typically created from `ReadFingerprintMap`, a map from `ReadAlignmentId` to `VString`.
/// The `Option<i32>` member for `ReadAlignmentId` allows us to have multiple fingerprints per read. (e.g., Kringle type IV repeat 2 aka KIV2).
#[derive(Debug, Default)]
pub struct Graph {
    pub settings: Settings,
    pub nvar: usize,
    pub reads: ReadFingerprintMap,
    pub reads_original: ReadFingerprintMap,
    pub graph: VGraph,
    read_aln_id_map: BTreeMap<ReadAlignmentId, u32>,
    pub node_id_map: NodeMapType, // Map from NodeDatum (hap, position) to index
    pub pos_edge_map: BTreeMap<usize, Vec<WeightedEdge>>, /* Vector from position to all the edges at that position. */
    pub edge_info: Vec<Vec<u32>>,                         // Vector of vectors of counts.
    pub dnhap: BTreeMap<u32, SegmentationClass>, /* Copy of dnhap from paraphase, except we use Option<i32> instead of i32 with -1 as a special case. */
    pub(crate) node_positions: HashMap<u32, (u32, u32)>,
    total_node_count: usize, /* Total number of nodes. Needed to maintain node numbering while handling deletions. */
}

impl std::ops::Deref for Graph {
    type Target = VGraph;
    fn deref(&self) -> &Self::Target {
        &self.graph
    }
}

impl std::ops::DerefMut for Graph {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.graph
    }
}

const ALPHABET: &[u8] = &[b'0', b'1', b'2', b'3', b'4', b'x', b'A', b'C', b'G', b'T'];

impl std::convert::TryFrom<&ParaphaseOutput> for Graph {
    type Error = GraphError;
    fn try_from(x: &ParaphaseOutput) -> Result<Self, Self::Error> {
        Self::try_from(x.clone())
    }
}

impl std::convert::TryFrom<ParaphaseOutput> for Graph {
    type Error = GraphError;
    fn try_from(x: ParaphaseOutput) -> Result<Self, Self::Error> {
        let pivot_index = x.pivot_index(None);
        Self::try_new(x.read_to_hap, Some(Settings::from_pivot(Some(pivot_index))))
    }
}

