/**
 * `Graph` class, port of the `Paraphase` equivalent class.
 * It is generated from a set of alignment ids (name + optional alignment number)
 * and associated fingerprints, as generated by alignments and variant site selection.
 *
 * The original implementation uses python structures to store nodes, edges,
 * and provide access to each.
 * We currently use a mix of petgraph and dictionary structures to support graph properties.
 *
 * `ReadAlignmentId` replaces the string names of reads.
 * This is because unlike Paraphase, we want to phase VNTRs, and it's therefore possible to have multiple alignments per read.
 * Most are straight ports, but typed.
 * We describe the exceptions here.
 * 1. For paralog/homolog phasing, there is simply no alignment id associated.
 *    This replaces `{read_name: read_hap}` for reads.
 * 2. The Graph Structure.
 *   In paraphase, it is made up of:
 *     List of edges
 *     List of nodes
 *     next-per-node and previous-per-node
 *     `edge_info`: map from edge to counts of supporting reads.
 *     `edge_per_position`: map from positions to edges
 *
 *  In `paraph-rs`, we use `petgraph` to store most of the data:
 *     We use a directed graph with `NodeType(String, position as u32)` as node type and `Vec<u32>` as edge type.
 *     These `u32`s identify which readalignments support the specific edge.
 *
 *  In addition to the graph structure, we have some helper objects.
 * `read_aln_id_map`: `HashMap` from `ReadAlignmentId` to a numeric id associated with it so that it's easy to pass around an identifier.
 * `node_id_map`: `HashMap` to look up a node's numeric id from the node value.
 *
 * `pos_edge_map` is a straight port of `edge_per_position`.
 * We do not store `edge_info` because its information is stored in `pos_edge_map`.
 *
 * When adding a node, one needs to update `id_node_by_map` to both get the id and see if it was newly inserted.
 *
 */

#[derive(Debug, Clone)]
pub struct GraphError {
    pub msg: String,
}

impl GraphError {
    #[must_use]
    pub fn new(x: impl Into<String>) -> Self {
        Self { msg: x.into() }
    }
}

impl std::error::Error for GraphError {}

impl std::fmt::Display for GraphError {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f, "GraphError{{msg: {}}}", self.msg)
    }
}

/// Class describing nature of the graph at a given position.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum SegmentationClass {
    Unassigned,
    Two, // Unambiguous: only one out edge
    Ten, // Ambiguous: multiple out edges
}

impl SegmentationClass {
    #[must_use]
    pub fn is_assigned(&self) -> bool {
        matches!(self, Self::Two | Self::Ten)
    }
}

