/// Maps from hap ids to read alignments (unique and ambiguous), as well as a map from read alignments
/// to potential hap ids.
/// Compared to the python implementation, we use numeric u32 ids for the provided fingerprints instead of a reference to the path itself for lifetime management ease.
#[derive(Clone)]
pub struct ReadHapSupport<'a> {
    pub support_reads: HashMap<u32, Vec<ReadHapPair<'a>>>, /* hap ids and their unique matches. Read alignments here have a unique haplotype match. */
    pub support_reads_nonunique: HashMap<u32, Vec<ReadHapPair<'a>>>, /* hap ids and their non-unique matches. Read alignments here have more than one candidate haplotype/fingerprint. */
    pub supporting_haps_per_read: HashMap<ReadHapPair<'a>, Vec<u32>>,
}

impl<'a> std::fmt::Debug for ReadHapSupport<'a> {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(
            f,
            "Support: {:?}\nAmbiguous Support: {:?}\n: HapsPerRead: {:?}",
            self.support_reads, self.support_reads_nonunique, self.supporting_haps_per_read
        )
    }
}

