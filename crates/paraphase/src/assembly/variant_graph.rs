        use crate::assembly::node_datum::NodeDatum;
        use crate::detail::util::DResult;
        use crate::io::json::{ReadAlignmentId, ReadFingerprintMap};
        #[test]
        fn test_graph_constructor_ok() -> DResult {
            use crate::assembly::variant_graph::*;
            use itertools::Itertools;
            let mut read_inputs = [
                ("r1", "11x"),
                ("r2", "11x"),
                ("r3", "22x"),
                ("r4", "22x"),
                ("r5", "x12"),
                ("r6", "x22"),
                ("r7", "x2x"),
                ("r8", "x22"),
                ("r9", "x11"),
                ("r10", "x11"),
                ("r11", "x22"),
                ("r12", "x22"),
                ("r13", "x22"),
                ("r14", "x22"),
                ("r15", "x11"),
                ("r16", "x11"),
                ("r17", "x11"),
                ("r18", "x11"),
            ]
            .into_iter()
            .map(|(x, y)| (ReadAlignmentId::from_name(x), vstr::VString::from(y)))
            .collect::<ReadFingerprintMap>();
            let mut graph = Graph::try_new(read_inputs.clone(), None)?;
            graph.init()?;
            let expected_nodes = [(1, 0), (1, 1), (1, 2), (2, 0), (2, 1), (2, 2)];
            let expected_nodes = expected_nodes
                .into_iter()
                .map(|(value, position)| {
                    let value = value as u8 + b'0';
                    NodeDatum::from((value, position as usize))
                })
                .sorted()
                .collect::<Vec<_>>();
            let nodes = graph.node_iter().cloned().sorted().collect::<Vec<_>>();
            assert_eq!(nodes, expected_nodes);
            let edges = graph
                .graph
                .edge_references()
                .map(|edge| {
                    graph
                        .paraphase_format_edge(edge.id(), None)
                        .expect("Edge missing")
                })
                .sorted()
                .collect::<Vec<(String, String)>>();

            let expected_edges = [
                ("1-0", "1-1"),
                ("2-0", "2-1"),
                ("2-1", "2-2"),
                ("1-1", "1-2"),
            ]
            .into_iter()
            .map(|(x, y)| (String::from(x), String::from(y)))
            .sorted()
            .collect::<Vec<(String, String)>>();
            assert_eq!(edges, expected_edges);

            assert!(!graph.reads.contains_key(&ReadAlignmentId::from_name("r5")));

            // Now remove node and test read allowance.
            // r5 should be present now.
            assert!(read_inputs
                .remove(&ReadAlignmentId::from_name("r18"))
                .is_some());

            let mut graph = Graph::try_new(read_inputs.clone(), None)?;
            graph.init()?;

            let nodes = graph.node_iter().cloned().sorted().collect::<Vec<_>>();
            assert_eq!(nodes, expected_nodes);

            let edges = graph
                .graph
                .edge_references()
                .map(|edge| {
                    graph
                        .paraphase_format_edge(edge.id(), None)
                        .expect("Nodes missing from graph.")
                })
                .sorted()
                .collect::<Vec<(String, String)>>();
            let expected_edges = [
                ("1-0", "1-1"),
                ("2-0", "2-1"),
                ("1-1", "2-2"),
                ("2-1", "2-2"),
                ("1-1", "1-2"),
            ]
            .into_iter()
            .map(|(x, y)| (String::from(x), String::from(y)))
            .sorted()
            .collect::<Vec<(String, String)>>();
            assert_eq!(edges, expected_edges);
            assert!(graph.reads.contains_key(&ReadAlignmentId::from_name("r5")));
            assert!(!graph.pos_edge_map.is_empty());
            {
                let map = &graph.pos_edge_map;
                log::debug!("Map: {map:?}");
                let format_edge = |edge: &WeightedEdge| -> (String, String, u32) {
                    let source = NodeIndex::new(edge.0 as usize);
                    let target = NodeIndex::new(edge.1 as usize);
                    let res = graph
                        .paraphase_format_edge(
                            graph
                                .find_edge(source, target)
                                .expect("Missing edge from graph"),
                            None,
                        )
                        .expect("Failed to format edge pair");
                    (res.0, res.1, edge.2)
                };
                assert_eq!(map.len(), 2);
                assert_eq!(map[&0].len(), 2);
                assert_eq!(map[&1].len(), 3);
                assert_eq!(
                    &map[&0].iter().map(format_edge).collect::<Vec<_>>()[..],
                    &[
                        (String::from("1-0"), String::from("1-1"), 2),
                        (String::from("2-0"), String::from("2-1"), 2)
                    ]
                );
            }
            Ok(())
        }
        #[test]
        fn summarize_edges_ok() -> DResult {
            use crate::assembly::variant_graph::SegmentationClass;
            use crate::assembly::variant_graph::SegmentationClass::*;
            use std::collections::BTreeMap;
            let read_inputs = [("r1", "11"), ("r2", "22")]
                .into_iter()
                .map(|(x, y)| (ReadAlignmentId::from_name(x), vstr::VString::from(y)))
                .collect::<ReadFingerprintMap>();
            let mut graph = crate::assembly::variant_graph::Graph::try_new(read_inputs, None)?;
            for node in [
                (b'1', 0), // 0
                (b'2', 0), // 1
                (b'1', 1), // 2
                (b'2', 1), // 3
                (b'1', 2), // 4
                (b'2', 2), // 5
                (b'1', 3), // 6
                (b'2', 3), // 7
                (b'1', 4), // 8
                (b'2', 4), // 9
            ]
            .into_iter()
            .map(|(chr, pos)| NodeDatum::from((chr, pos as usize)))
            {
                let (_id, was_new) = graph.fully_add_node(node);
                assert!(was_new);
            }
            assert_eq!(graph.total_node_count, 10);
            assert_eq!(graph.node_id_map.len(), 10);
            let mut edges: BTreeMap<usize, Vec<(u32, u32, u32)>> = BTreeMap::new();
            edges.insert(0, vec![(0, 2, 2), (1, 3, 3)]);
            edges.insert(1, vec![(2, 5, 2), (3, 5, 6), (2, 4, 5)]);
            edges.insert(2, vec![(4, 7, 2), (5, 7, 6), (4, 6, 5)]);
            edges.insert(3, vec![(6, 9, 2), (7, 9, 6), (6, 8, 5)]);
            /*
            let edges = vec![
                vec![(0, 2, 2), (1, 3, 3)],
                vec![(2, 5, 2), (3, 5, 6), (2, 4, 5)],
                vec![(4, 7, 2), (5, 7, 6), (4, 6, 5)],
                vec![(6, 9, 2), (7, 9, 6), (6, 8, 5)], /* [("1-3", "2-4", 2), ("2-3", "2-4", 6), ("1-3", "1-4", 5)], */
            ];
            */
            for (_idx, edge_set) in &edges {
                for (from, to, _count) in edge_set {
                    //for (from, to, _count) in edges.iter().flatten().copied() {
                    graph.add_edge((*from).into(), (*to).into(), vec![]);
                }
            }
            graph.pos_edge_map = edges;
            graph.summarize_edges()?;
            let expected_dnhap = [(0, Two), (1, Ten), (2, Ten), (3, Ten)]
                .into_iter()
                .collect::<BTreeMap<u32, SegmentationClass>>();
            log::debug!("Found {:?} dnhap, expected {expected_dnhap:?}", graph.dnhap);
            assert_eq!(expected_dnhap, graph.dnhap);
            Ok(())
        }
